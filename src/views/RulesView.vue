      <li><b>威胁提示</b>：任何一方下出活三、冲四这类棋形时提醒你，并标出要挡的点。</li>
      <li><b>棋盘标记</b>：朱色小点是最后一手（显示手数时改为套一圈）；套在棋子上的红圈表示连五、禁手判负或陪练说到的那手；空点上的虚线圈是要挡的点（红）或自己的进攻点（绿），实线绿圈是推荐的点；实心绿圆片是「提示」的候选点；红叉是黑方的禁手点。</li>
      <li><b>实时胜率</b>：胜率条和「数据」里的走势图，显示双方当前的形势。</li>
      <li><b>陪练</b>：在对弈页「设置」页签的陪练一栏中打开，可以请棋馆的老茶客老陈、隔壁茶铺的小棠或书院的小晴坐在旁边。开局时会按对手的棋风提醒一句；你下松了，等对手应完再说出更好的位置。平时陪练只说话，不在棋盘上画标记；只有「失误提醒」暂停对局时，才在棋盘上标出来：打「？」的是你那手，绿圈是更好的点，红虚线圈是对方接下来的应手。话里的坐标指上去，棋盘上那一点会闪一下。活三、冲四、活四、四三、双活三，以及连珠的禁手、标准五子棋的长连，每盘第一次出现时，也会顺带讲一句是什么意思（大师难度不讲）。</li>
      <li><b>失误提醒</b>：在对弈页「设置」页签的陪练一栏中设置，分三档。「关闭」：不打断对局，由陪练在落子后点评；「仅致命失误」：落子后将直接输棋，或错过了连续冲四的胜机时，先暂停对局并说明；「所有明显失误」：胜率明显下降的着法也会先暂停并说明。暂停时可以选择仍下此处，或撤回并改下陪练建议的位置。双人对弈时陪练只描述局面，不指点下法、不提示胜机，也不作失误提醒；双方的失误留到对局结束后「跟陪练复盘」时一并讲解。</li>
      <li><b>跟陪练复盘</b>：下完一盘，结算卡上点「跟老陈复盘」（或者「复盘要点」旁边的链接），陪练挑出胜率掉得最多的至多三手，一处一处讲：你下的、更好的、对方会怎么罚；「看后面怎么走」把实战之后的手顺（或者放过的连续冲四）按顺序摆出来。</li>
      <li><b>复盘</b>：点棋谱里的任意一手，或走势图上的任意一点，就进入复盘。棋盘上的灰色虚影是实战的下一手，绿圈是这个局面的推荐下法；点「从此处继续」可以从这里重新下。</li>
      <li><b>败着标注</b>：让形势明显变差的一手标「?」，严重失误标「??」，都汇总在「复盘要点」里。要打开实时胜率才有。</li>
      <li><b>棋风读数</b>：双方各下几手以后，从四个方面描绘棋风：防守还是进攻，爱走横竖还是斜线，各下各的还是贴着对方下，占中心还是往边角。红色竖线是这位对手平时的样子，能看出它这盘是否反常，也能看出你的下法最像哪位对手。它只看棋子的位置关系，不会透露该下哪里。</li>
