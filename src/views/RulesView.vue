    <summary>定式</summary>
    <ul>
      <li>收录连珠 26 种标准开局，定式约 4 万着，主线多数能走到二三十手以后。定式、开局评价和电脑推荐都按连珠规则（黑方有禁手）；在无禁手或标准五子棋下，部分结论并不成立。</li>
      <li><b>翻谱</b>：在开局列表里选一个开局，用棋盘下面的 ◀ ▶ 一手一手翻，⏭ 沿主线走到底。也可以直接点棋盘上的数字，1 号是主线。</li>
      <li><b>颜色</b>：
        <span class="r-lg"><i class="book"></i><b>红色</b>是定式</span>；
        <span class="r-lg"><i class="ai"></i><b>蓝色</b>是开局库补充的下法</span>，附电脑估计的胜率；
        <span class="r-lg"><i class="engine"></i><b>绿色</b>是出谱以后电脑现算的</span>（电脑推荐、续推、算杀）。虚线圈是谱上标明的疑问手。</li>
      <li><b>出谱以后</b>：改由电脑推荐下法。「更多」里还能让电脑续推几手，或者算连续冲四的杀法。</li>
      <li><b>练习</b>：点「执黑练习」或「执白练习」，就在定式页的棋盘上从当前局面开始练。电脑按谱应；你每下一手都当场对照谱，出谱时会标出谱上的下法，你可以悔一步换一手，也可以接着下，出谱后电脑按最强难度应对。练习不用对弈的对手、难度和陪练设置，也不计战绩；想和对手下完这盘，点「到对弈里下完」。按谱走完一条定式、中途没有出谱，这个开局就记为「练通」，主页定式卡上会标出来。</li>
      <li>对弈时不显示定式，「提示」给的是电脑推荐的候选点。</li>
    </ul>
