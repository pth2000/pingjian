      <dt>直指 / 斜指</dt><dd>第 2 手白子与天元的黑子横竖相邻（直指），或斜向相邻（斜指）。</dd>
      <dt>假先方 / 假后方</dt><dd>开局规则中先摆开局的一方 / 另一方。开局结束后才最终确定谁执黑。</dd>
      <dt>交换</dt><dd>开局规则中，一方放弃当前的颜色，改执对方的颜色。</dd>
      <dt>防点 / 打点</dt><dd>白 4 的防守位置 / 黑方为第 5 手提供的候选位置，由白方从中选定一个。「五手二打」指提供两个打点。</dd>
      <dt>连五</dt><dd>同色五子连成一线。</dd>
      <dt>长连</dt><dd>同色六子或六子以上连成一线。连珠中是黑方的禁手，标准五子棋中不计胜，无禁手规则中计胜。</dd>
      <dt>活四</dt><dd>两端都能形成连五的四子，对方无法同时防守。</dd>
      <dt>冲四</dt><dd>只有一个点能形成连五的四子。</dd>
      <dt>活三</dt><dd>再下一手即可形成活四的三子。</dd>
      <dt>四三</dt><dd>一手同时形成冲四和活三，通常可以取胜。</dd>
      <dt>三三 / 四四</dt><dd>一手同时形成两个活三 / 两个四（活四或冲四）。连珠中均为黑方的禁手。</dd>
      <dt>VCF</dt><dd>连续冲四取胜。</dd>
      <dt>VCT</dt><dd>以连续的活三、冲四取胜。</dd>
      <dt>出谱</dt><dd>下出谱中没有记载的着法。</dd>
